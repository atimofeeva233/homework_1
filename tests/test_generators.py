@pytest.mark.parametrize("start,end,expected_first,expected_last,expected_count", [
    (1, 1, "0000 0000 0000 0001", "0000 0000 0000 0001", 1),
    (9999, 10001, "0000 0000 0000 9999", "0000 0000 0001 0001", 3),
    (1234567890123456, 1234567890123458,
     "1234 5678 9012 3456", "1234 5678 9012 3458", 3),
    (9999999999999997, 9999999999999999,
     "9999 9999 9999 9997", "9999 9999 9999 9999", 3),
])
def test_card_number_generator_parametrized(start, end, expected_first, expected_last, expected_count):
    """Параметризованный тест генератора"""
    result = list(card_number_generator(start, end))

    assert len(result) == expected_count
    assert result[0] == expected_first
    assert result[-1] == expected_last
